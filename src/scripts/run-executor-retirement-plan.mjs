const readTable = (table, predicate) => `SELECT '${table}' AS table,id,parent_id,path,to_jsonb(t) body
  FROM public."${table}" t WHERE id > COALESCE($1,0) AND ${predicate}
  ORDER BY id LIMIT $2`

export const retirementPlan = {
  artifactPath: 'src/scripts/run-executor-retirement-plan.mjs',
  estimatedQueries: 80,
  async snapshot({ readPages }) {
    const targetRows = []
    const protectedRows = []
    for (const table of relationTables) {
      targetRows.push(...await readPages(`target:${table}`, readTable(table, 'path ~ $3'),
        (cursor, limit) => [cursor, limit, legacyPath], (row) => row.id))
      protectedRows.push(...await readPages(`protected:${table}`, readTable(table, 'path !~ $3'),
        (cursor, limit) => [cursor, limit, legacyPath], (row) => row.id))
    }
    const canonicalRows = await readPages('canonical',
      'SELECT id,to_jsonb(t) body FROM travel_memories t WHERE id > COALESCE($1,0) ORDER BY id LIMIT $2',
      (cursor, limit) => [cursor, limit], (row) => row.id)
    const legacyRows = await readPages('legacy',
      `SELECT id,to_jsonb(t) body FROM ${legacyTable} t WHERE id > COALESCE($1,0) ORDER BY id LIMIT $2`,
      (cursor, limit) => [cursor, limit], (row) => row.id).catch((error) => {
        if (error?.code === '42P01') return [] // after an expected DROP only
        throw error
      })
    const metadata = {}
    for (const [name, sql] of Object.entries(metadataSql)) {
      metadata[name] = await readPages(`metadata:${name}`, sql,
        (cursor, limit) => name === 'sequences' ? [cursor, limit] : [cursor, limit, tables], (row) => row.id).catch((error) => {
        if (name === 'sequences' && error?.code === '42P01') return [] // after an expected DROP only
        throw error
      })
    }
    return { targetRows, protectedRows, canonicalRows, legacyRows, metadata }
  },
  async apply({ backup, query, rowCap }) {
    for (const table of relationTables) {
      const rows = backup.targetRows.filter((row) => row.table === table)
      for (let offset = 0; offset < rows.length; offset += rowCap) {
        const batch = rows.slice(offset, offset + rowCap)
        const sql = `DELETE FROM public."${table}" t USING jsonb_to_recordset($1::jsonb)
          AS expected(id integer,parent_id integer,path text) WHERE t.id=expected.id
          AND t.parent_id=expected.parent_id AND t.path=expected.path RETURNING t.id`
        const deleted = await query(`delete:${table}`, sql,
          [JSON.stringify(batch.map(({ id, parent_id, path }) => ({ id, parent_id, path })))], offset / rowCap + 1)
        assert.deepEqual(deleted.map((row) => row.id).sort((a, b) => a - b), batch.map((row) => row.id).sort((a, b) => a - b),
          'BLOCK: exact delete cardinality')
      }
    }
    await query('drop:legacy', `DROP TABLE public."${legacyTable}" RESTRICT`)
  },
  assertAfter(before, after) {
    if (after.targetRows.length || after.legacyRows.length) throw new RunBlock('TARGET_REMAINS')
    assert.deepEqual(after.protectedRows, before.protectedRows, 'BLOCK: non-target read-back')
    assert.deepEqual(after.canonicalRows, before.canonicalRows, 'BLOCK: canonical read-back')
    for (const [key, rows] of Object.entries(before.metadata)) {
      const expected = rows.filter((row) => !row.id.startsWith(`${legacyTable}.`) &&
        row.id !== legacyTable && row.id !== `${legacyTable}_id_seq`)
      assert.deepEqual(after.metadata[key], expected, `BLOCK: ${key} read-back`)
    }
  },
  async restore({ backup, query }) {
    await query('restore:table', `CREATE TABLE ${legacyTable} (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      _parent_id integer NOT NULL REFERENCES travel_memories(id),
      _order integer NOT NULL,day integer NOT NULL,date_label text)`)
    await query('restore:index', `CREATE INDEX travel_memories_daily_highlights_parent_id_idx ON ${legacyTable}(_parent_id)`)
    await query('restore:rls', `ALTER TABLE ${legacyTable} ENABLE ROW LEVEL SECURITY`)
    await query('restore:policy', `CREATE POLICY retirement_read ON ${legacyTable} FOR SELECT TO retirement_reader USING (true)`)
    await query('restore:grant', `GRANT SELECT ON ${legacyTable} TO retirement_reader`)
    await query('restore:rows', `INSERT INTO ${legacyTable} SELECT * FROM json_populate_recordset(NULL::${legacyTable},$1::json)`,
      [JSON.stringify(backup.legacyRows.map((row) => row.body))])
    const sequence = backup.metadata.sequences.find((row) => row.sequencename === `${legacyTable}_id_seq`)
    assert(sequence && sequence.last_value !== null, 'BLOCK: sequence backup missing')
    await query('restore:sequence', `SELECT setval('${legacyTable}_id_seq',$1,$2)`, [sequence.last_value, sequence.is_called])
    for (const table of relationTables) {
      const rows = backup.targetRows.filter((row) => row.table === table).map((row) => row.body)
      await query(`restore:${table}`, `INSERT INTO public."${table}" SELECT * FROM json_populate_recordset(NULL::public."${table}",$1::json)`, [JSON.stringify(rows)])
    }
  },
}

export function backupFromSnapshot(snapshot) {
  // The raw backup file is also bound by the manifest SHA-256.
  return { version: 1, snapshot, snapshotSha256: createHash('sha256').update(stable(snapshot)).digest('hex') }
}

const stable = (value) => JSON.stringify(value, (_, item) => item && !Array.isArray(item) && typeof item === 'object'
  ? Object.fromEntries(Object.keys(item).sort().map((key) => [key, item[key]])) : item)
